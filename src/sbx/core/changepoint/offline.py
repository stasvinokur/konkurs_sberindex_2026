"""Вход офлайн-методов в единицах шума и эталон «тревога по расписанию».

Штраф офлайн-метода — это цена разреза в единицах стоимости сегмента. У квадратичной
стоимости она измеряется в квадрате единиц ряда, а ряды панели различаются по уровню на два
порядка: штраф, осмысленный для ряда в сотни рублей, для ряда в десятки тысяч ничего не
стоит, и метод режет такой ряд в каждой допустимой точке. Поэтому перед поиском сломов ряд
переводится в единицы собственного шума, и один штраф означает одно и то же для всех рядов.
"""

from __future__ import annotations

from collections.abc import Sequence

import numpy as np


def noise_scale(values: Sequence[float]) -> float:
    """Робастная оценка стандартного отклонения шума ряда по его первым разностям.

    Оценка — 1,4826·MAD(Δy)/√2. Она не растёт от того, что метод ищет: сдвиг уровня даёт одну
    большую разность, сезонный пик — две, и медиана их не замечает; постоянный тренд сдвигает
    все разности одинаково и из MAD выпадает. Оценка по самому ряду раздувалась бы сломом и
    прятала бы его.

    Если MAD нулевой (больше половины разностей одинаковы), берётся разброс разностей; если
    ряд постоянен или его разности равны с точностью до округления, масштаб равен единице.
    """
    values = np.asarray(values, dtype=float)
    diffs = np.diff(values)
    if len(diffs) == 0:
        return 1.0
    # Разброс меньше ошибки округления шумом не считается: иначе ровная прямая в «единицах
    # шума» превращается в числа порядка 1e17.
    rounding = 1e-9 * max(float(np.max(np.abs(values))), 1.0)
    mad = float(np.median(np.abs(diffs - np.median(diffs))))
    scale = 1.4826 * mad if mad > rounding else float(np.std(diffs))
    return scale / np.sqrt(2.0) if scale > rounding else 1.0


def to_noise_units(values: Sequence[float]) -> np.ndarray:
    """Ряд, отсчитанный от своей медианы, в единицах собственного шума."""
    values = np.asarray(values, dtype=float)
    return (values - np.median(values)) / noise_scale(values)


def periodic_alarms(n: int, period: int) -> list[int]:
    """Тревога по расписанию: каждые `period` точек, не глядя на данные.

    Эталон для сравнения детекторов: метод, который не лучше расписания, ничего не находит.
    """
    if period <= 0:
        raise ValueError(f"период должен быть положительным, получено {period}")
    return list(range(period, n, period))
