REGIONS: dict[str, Region] = {}
for _line in _RAW.strip().splitlines():
    _code, _name, _fd = _line.split("|")
    REGIONS[_code] = Region(_code, _name, _FD[_fd])

# Автономные округа внутри составных субъектов различаются 3-й цифрой ОКТМО.
SUBREGIONS: dict[str, Region] = {
    "118": Region("118", "Ненецкий автономный округ", _FD["СЗФО"]),
    "718": Region("718", "Ханты-Мансийский автономный округ — Югра", _FD["УФО"]),
    "719": Region("719", "Ямало-Ненецкий автономный округ", _FD["УФО"]),
}


def region_of_oktmo(oktmo: str) -> Region | None:
    """Субъект РФ по коду ОКТМО (с учётом автономных округов в составе областей)."""
    code = str(oktmo).strip()
    if len(code) < 2:
        return None
    return SUBREGIONS.get(code[:3]) or REGIONS.get(code[:2])


def region_by_code(code: str) -> Region:
    return SUBREGIONS.get(code) or REGIONS[code]
